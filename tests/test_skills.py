def experiment(hypothesis="h [stop-rule v1 n=1000 early=0.9987 final=0.95 guard=0.95]", status="running", arms=("b",),
               split=50.0):
    return {
        "id": 7, "status": status, "hypothesis": hypothesis,
        "feature": {"multivariate_options": [{"id": 10 + i, "key": k} for i, k in enumerate(arms)]},
        "experiment_rollout": {"multivariate_feature_state_values": [
            {"multivariate_feature_option": 10 + i, "percentage_allocation": split} for i, _ in enumerate(arms)]},
        "metrics": [
            {"metric": 1, "metric_name": "purchase", "direction": "up", "expected_direction": "increase"},
            {"metric": 2, "metric_name": "refunds", "direction": "down", "expected_direction": "not_increase"},
        ],
        "rollout_decision": None, "rollout_variant": None,
    }


def at(seconds: int) -> str:
    """An ISO instant `seconds` after the epoch, the shape Flagsmith returns."""
    from datetime import datetime, timedelta, timezone

    return (datetime.fromtimestamp(0, timezone.utc) + timedelta(seconds=seconds)).isoformat()


def results(n=500, chance=0.97, refunds_ctw=0.5, arms=("b",), n_arm=None, requested=at(0), as_of=at(1), error=None):
    def metric(mid, ctw):
        return {"metric_id": mid,
                "variants": {"control": {"n": n}, **{a: {"n": n_arm or n} for a in arms}},
                "inference": {a: (None if ctw is None else {"lift": 0.1, "ci_low": -0.02, "ci_high": 0.22,
                                                            "chance_to_win": ctw}) for a in arms}}
    return {"results": {"as_of": as_of, "refresh_requested_at": requested, "last_error_at": error, "is_final": False,
                        "payload": {"metrics": [metric(1, chance), metric(2, refunds_ctw)], "srm_p_value": None}}}


