def api_paths(text: str) -> set[str]:
    text = text.replace("$A", "api/v1/environments/$E/experiments/$X")
    raw = re.findall(r"(?:api/v1/|\.\.\./)(environments/[^\s\"'`)|]+|experiments/[^\s\"'`)|]+)", text)
    out = set()
    for p in raw:
        p = p.split("?")[0].rstrip(".,")
        p = p if p.endswith("/") else p + "/"
        if p.startswith("experiments/"):
            p = "environments/E/" + p
        p = re.sub(r"^environments/(?:\$E|E|<[^>]+>)/", "environments/{e}/", p)
        p = re.sub(r"/experiments/(?:\$X|X|<[^>]+>|\d+)/", "/experiments/{x}/", p)
        out.add(p)
    return out


