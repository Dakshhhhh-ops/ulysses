def code_segments(text: str) -> tuple[list[str], list[str]]:
    """(lines inside fenced code blocks, inline code spans), comments removed."""
    blocks, spans = [], []
    for block in re.findall(r"```[a-z]*\n(.*?)```", text, re.S):
        blocks += re.sub(r"\\\n\s*", " ", block).splitlines()  # join shell line continuations
    outside = re.sub(r"```[a-z]*\n.*?```", "", text, flags=re.S)
    spans += re.findall(r"`([^`\n]+)`", outside)
    return blocks, spans


def commands(text: str, prog: str) -> list[tuple[list[str], bool]]:
    """Each `prog ...` invocation as tokens, and whether it came from a code block."""
    blocks, spans = code_segments(text)
    found = []
    for src, in_block in [(b, True) for b in blocks] + [(s, False) for s in spans]:
        src = re.sub(r"(?<![\w'\"])#.*$", "", src)
        for seg in re.split(r";|\||&&|\{|\}|\$\(|\)\s", src):
            seg = seg.strip().strip(")")
            if seg.startswith("uv run "):
                seg = seg[len("uv run "):]
            if not seg.startswith(prog + " ") and seg != prog:
                continue
            seg = re.sub(r"<<'?EOF'?", "", seg)
            seg = re.sub(r"\[(--[^\]]+)\]", r"\1", seg)
            try:
                toks = shlex.split(seg)
            except ValueError:
                toks = seg.split()
            found.append((toks, in_block))
    return found


