def frontmatter(text: str) -> tuple[dict, str]:
    """A strict reader for the subset of YAML the skills use: `key: value` and one nested string map."""
    assert text.startswith("---\n"), "SKILL.md must start with a --- frontmatter line"
    head, sep, body = text[4:].partition("\n---\n")
    assert sep, "frontmatter is not closed with ---"
    out: dict = {}
    current = None
    for line in head.splitlines():
        if not line.strip():
            continue
        if line.startswith("  "):
            assert current is not None and isinstance(out[current], dict), f"unexpected indented line {line!r}"
            k, _, v = line.strip().partition(": ")
            out[current][k] = v.strip().strip('"')
            continue
        k, colon, v = line.partition(":")
        assert colon, f"not a key: value line: {line!r}"
        v = v.strip()
        assert ": " not in v and not v.startswith(("'", "[", "{", "&", "*", "!", "|", ">")), \
            f"{k}: keep values plain one-line scalars ({v[:40]!r})"
        out[k] = v if v else {}
        current = k
    return out, body


