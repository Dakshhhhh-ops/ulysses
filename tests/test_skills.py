def test_every_flagsmith_cli_command_and_flag_exists():
    seen = 0
    for toks, _ in commands(all_skill_text(), "flagsmith"):
        words = [t for t in toks[1:] if not t.startswith("-")]
        flags = {t.split("=")[0] for t in toks[1:] if t.startswith("-") and t != "-"}
        if not words:
            assert flags <= GLOBAL, toks
            continue
        words[0] = ALIASES.get(words[0], words[0])
        path = next((tuple(words[:n]) for n in (3, 2, 1) if tuple(words[:n]) in CLI), None)
        assert path is not None, f"not a Flagsmith CLI v2 command: {' '.join(toks)}"
        bad = flags - CLI[path] - GLOBAL
        assert not bad, f"{' '.join(path)} has no flag {bad}: {' '.join(toks)}"
        seen += 1
    assert seen >= 25


def _fill(tok: str) -> str:
    tok = tok.replace('"$H"', "sha256:" + "a" * 64).replace("$H", "sha256:" + "a" * 64)
    tok = tok.replace("$X", "7").replace("$E", "envkey")
    return re.sub(r"<[^>]+>", "x", tok)


