def test_guardrail_orientation_and_breaches():
    # refunds is a `down` metric: Flagsmith's chance_to_win is the chance it fell, so worse = 1 - ctw
    v = sr.check(experiment(), results(n=500, chance=0.5, refunds_ctw=0.0005))
    assert v["verdict"] == "KEEP_CONTROL" and "refunds" in v["why"]
    assert v["guardrails"][0]["worse"] == pytest.approx(0.9995)
    blocked = sr.check(experiment(), results(n=1000, chance=0.99, refunds_ctw=0.03))
    assert blocked["verdict"] == "KEEP_CONTROL" and "guardrail" in blocked["why"]
    fine = sr.check(experiment(), results(n=1000, chance=0.99, refunds_ctw=0.9))
    assert fine["verdict"] == "SHIP"


